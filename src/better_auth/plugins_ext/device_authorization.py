"""device-authorization plugin — OAuth 2.0 Device Authorization Grant (RFC 8628).

TV/CLI login: a device mints a `device_code`/`user_code` pair, shows the user_code to
the user, and polls `/device/token` while the user visits `/device` on a second screen
(phone/laptop) to approve or deny it.

Verified against TS ``packages/better-auth/src/plugins/device-authorization/``
(``index.ts``, ``routes.ts``, ``schema.ts``, ``error-codes.ts``) at v1.7.6. Every error
in this plugin is OAuth-shaped on the wire (``{"error": ..., "error_description": ...}``,
RFC 6749 style) rather than this port's generic ``{"code", "message"}`` APIError body, so
errors travel as :class:`DeviceAuthorizationError` and render through ``to_response``.

A :class:`DeviceAuthorizationGrant` (TS ``DeviceAuthorizationGrant``) lets a token issuer
such as the OAuth provider own some codes: it authorizes the request, adds its own
``deviceCode`` columns, keeps its codes out of ``/device/token`` and adds owner-only context
to ``GET /device``. :func:`redeem_device_code` is the polling and one-time claim state machine
every issuer shares.

Redemption of an approved code is atomic (``adapter.consume_one`` — delete-and-return, TS
``consumeOne``): concurrent pollers race on the same delete, exactly one wins the row, every
other caller gets ``None`` back and is rejected. The `/device` claim of a pending, unbound
code and the `/device/token` polling-interval bump both use ``adapter.increment_one``
(guarded compare-and-swap, TS ``incrementOne``) so a stale read can never clobber a write
that landed first. This closes the same race TS's own GHSA-cq3f-vc6p-68fh fix targets, and
hardens the (TS-unguarded) `lastPolledAt` bump the same way.
"""

